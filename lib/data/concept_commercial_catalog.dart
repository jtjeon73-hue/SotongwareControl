/// Commercial metadata per concept seed — shared across artifact variants.
library;

import 'concept_catalog.dart';

class ConceptCommercialCatalog {
  ConceptCommercialCatalog._();

  static ConceptCommercialMeta? forSeedId(String seedId) {
    final meta = bySeedId[seedId];
    return isComplete(meta) ? meta : null;
  }

  static ConceptCommercialMeta requireForSeedId(String seedId) {
    final meta = forSeedId(seedId);
    if (meta == null) {
      throw StateError(
        'Missing or incomplete commercial meta for seed: $seedId',
      );
    }
    return meta;
  }

  static bool isComplete(ConceptCommercialMeta? m) {
    if (m == null) return false;
    if (m.customerProblem.trim().isEmpty) return false;
    if (m.promisedOutcome.trim().isEmpty) return false;
    if (m.reasonsToPay.isEmpty) return false;
    if (m.uniqueValue.trim().isEmpty) return false;
    if (m.recommendationReason.trim().isEmpty) return false;
    if (m.monetizationModels.isEmpty) return false;
    return true;
  }

  static ConceptCommercialMeta resolve(ConceptSeed seed) {
    if (isComplete(seed.commercial)) return seed.commercial!;
    final mapped = bySeedId[seed.id];
    if (isComplete(mapped)) return mapped!;
    if (seed.active && !seed.deprecated) {
      throw StateError('Missing commercial meta for active seed: ${seed.id}');
    }
    throw StateError('Missing commercial meta for seed: ${seed.id}');
  }

  static String seedIdFromCandidateId(String candidateId) {
    final idx = candidateId.lastIndexOf('__');
    if (idx <= 0) return candidateId;
    return candidateId.substring(0, idx);
  }

